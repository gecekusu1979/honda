        public static void Generate(string outputPath)
        {
            byte[] rom = new byte[P28Offsets.RomSize];

            // Fuel map yaz
            WriteMap(rom, P28Offsets.FuelMap, StockFuelMap);

            // Ignition map yaz
            WriteMap(rom, P28Offsets.IgnitionMap, StockIgnitionMap);

            // VTEC RPM: 4800 (0x12C0)
            rom[P28Offsets.VtecRpmThreshold]     = 0x12;
            rom[P28Offsets.VtecRpmThreshold + 1] = 0xC0;

            // Rev limit: 7200 (0x1C20)
            rom[P28Offsets.RevLimit]     = 0x1C;
            rom[P28Offsets.RevLimit + 1] = 0x20;

            // Checksum hesapla
            byte xor = 0;
            for (int i = 0; i < rom.Length - 1; i++) xor ^= rom[i];
            rom[P28Offsets.ChecksumByte] = xor;

            File.WriteAllBytes(outputPath, rom);
            Console.WriteLine($"Test ROM oluşturuldu: {outputPath}");
        }

        private static void WriteMap(byte[] rom, int offset, byte[,] map)
        {
            int rows = map.GetLength(0);
            int cols = map.GetLength(1);
            for (int r = 0; r < rows; r++)
                for (int c = 0; c < cols; c++)
                    rom[offset + (r * cols) + c] = map[r, c];
        }
